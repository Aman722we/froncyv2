async def seed_companies_and_bundles(conn) -> None:
    """
    Seeds all covered companies into the companies table,
    links career_sources and manual_jobs, cleans legacy suffixes,
    and upserts the 7 curated bundles with member companies.
    """
    try:
        # 1. Backfill companies from distinct career_sources
        await conn.execute("""
            INSERT INTO companies (name)
            SELECT DISTINCT trim(company_name)
            FROM career_sources
            WHERE company_name IS NOT NULL AND trim(company_name) != ''
            ON CONFLICT (name) DO NOTHING;
        """)

        # 2. Seed all 529 directory companies
        await conn.executemany("""
            INSERT INTO companies (name)
            VALUES ($1)
            ON CONFLICT (name) DO NOTHING;
        """, [(cname,) for cname in COVERED_COMPANIES])

        # 3. Clean any legacy ' India' rows if present
        india_rows = await conn.fetch("SELECT id, name FROM companies WHERE name ILIKE '% India'")
        for r in india_rows:
            old_id = r["id"]
            old_name = r["name"]
            base_name = old_name[:-6].strip()
            base_row = await conn.fetchrow("SELECT id FROM companies WHERE name = $1", base_name)
            if base_row:
                new_id = base_row["id"]
                await conn.execute("UPDATE career_sources SET company_id = $1, company_name = $2 WHERE company_id = $3 OR company_name = $4", new_id, base_name, old_id, old_name)
                await conn.execute("UPDATE manual_jobs SET company_id = $1, company = $2 WHERE company_id = $3 OR company = $4", new_id, base_name, old_id, old_name)
                await conn.execute("DELETE FROM company_bundle_members WHERE company_id = $1 AND bundle_id IN (SELECT bundle_id FROM company_bundle_members WHERE company_id = $2)", old_id, new_id)
                await conn.execute("UPDATE company_bundle_members SET company_id = $1 WHERE company_id = $2", new_id, old_id)
                await conn.execute("DELETE FROM user_company_prefs WHERE company_id = $1 AND telegram_id IN (SELECT telegram_id FROM user_company_prefs WHERE company_id = $2)", old_id, new_id)
                await conn.execute("UPDATE user_company_prefs SET company_id = $1 WHERE company_id = $2", new_id, old_id)
                await conn.execute("DELETE FROM companies WHERE id = $1", old_id)
            else:
                await conn.execute("UPDATE companies SET name = $1 WHERE id = $2", base_name, old_id)
                await conn.execute("UPDATE career_sources SET company_name = $1 WHERE company_id = $2 OR company_name = $3", base_name, old_id, old_name)
                await conn.execute("UPDATE manual_jobs SET company = $1 WHERE company_id = $2 OR company = $3", base_name, old_id, old_name)

        # 4. Link career_sources.company_id
        await conn.execute("""
            UPDATE career_sources cs
            SET company_id = c.id
            FROM companies c
            WHERE cs.company_id IS NULL AND trim(cs.company_name) = c.name;
        """)

        # 5. Link manual_jobs.company_id
        await conn.execute("""
            UPDATE manual_jobs mj
            SET company_id = c.id
            FROM companies c
            WHERE mj.company_id IS NULL AND lower(trim(mj.company)) = lower(c.name);
        """)

        # 6. Remove obsolete bundles not in active list
        active_slugs = [b["slug"] for b in CURATED_BUNDLES]
        placeholders = ", ".join(f"'{s}'" for s in active_slugs)
        await conn.execute(f"DELETE FROM company_bundles WHERE slug NOT IN ({placeholders});")

        # 7. Upsert the 7 curated bundles
        for b in CURATED_BUNDLES:
            await conn.execute("""
                INSERT INTO company_bundles (name, emoji, slug, description)
                VALUES ($1, $2, $3, $4)
                ON CONFLICT (slug) DO UPDATE
                SET name = EXCLUDED.name,
                    emoji = EXCLUDED.emoji,
                    description = EXCLUDED.description;
            """, b["name"], b["emoji"], b["slug"], b["description"])

        # 8. Seed bundle members
        for b in CURATED_BUNDLES:
            bslug = b["slug"]
            cnames = b["companies"]
            escaped_cnames = ", ".join(f"'{c.replace(chr(39), chr(39)+chr(39))}'" for c in cnames)
            
            # Clean obsolete members
            await conn.execute(f"""
                DELETE FROM company_bundle_members
                WHERE bundle_id = (SELECT id FROM company_bundles WHERE slug = '{bslug}')
                  AND company_id NOT IN (SELECT id FROM companies WHERE name IN ({escaped_cnames}));
            """)

            # Bulk insert members
            await conn.execute(f"""
                INSERT INTO company_bundle_members (bundle_id, company_id)
                SELECT b.id, c.id
                FROM company_bundles b
                CROSS JOIN companies c
                WHERE b.slug = '{bslug}' AND c.name IN ({escaped_cnames})
                ON CONFLICT DO NOTHING;
            """)

        logger.info(f"Successfully seeded {len(COVERED_COMPANIES)} companies and {len(CURATED_BUNDLES)} bundles.")
    except Exception as e:
        logger.warning(f"Failed to seed companies and bundles: {e}")
